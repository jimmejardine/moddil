//! The `.pyi` stubs: the module's types, for editors and type checkers. A submodule is written as
//! a class of its name holding its functions (as static methods) and classes, its classes named
//! by their path (`geo.Rect`).

use std::fmt::Write as _;

use crate::{Callable, Gen, PyTy};

fn py(g: &Gen<'_>, t: &PyTy) -> String {
    match t {
        PyTy::Unit => "None".to_string(),
        PyTy::Bool => "bool".to_string(),
        PyTy::Int(..) => "int".to_string(),
        PyTy::Float(..) => "float".to_string(),
        PyTy::Str | PyTy::String => "str".to_string(),
        PyTy::Slice(..) => "Buffer".to_string(),
        PyTy::Vec(e) if e.moddil == "u8" => "bytes".to_string(),
        PyTy::Vec(e) => format!("Array[{}]", if e.kind == 'f' { "float" } else { "int" }),
        PyTy::Option(inner) => format!("{} | None", py(g, inner)),
        PyTy::Struct(a, _) => {
            let path: String = g.module_of(*a).iter().map(|p| format!("{p}.")).collect();
            format!("{path}{}", g.sname(*a))
        }
    }
}

fn sig(g: &Gen<'_>, c: &Callable, this: bool) -> String {
    let mut ps: Vec<String> = Vec::new();
    if this {
        ps.push("self".to_string());
    }
    for (n, t) in &c.params {
        ps.push(format!("{n}: {}", py(g, t)));
    }
    ps.join(", ")
}

/// The path of the module inside the mod that declares function `f`.
fn fn_module<'a>(g: &'a Gen<'_>, f: u32) -> &'a [String] {
    &g.items.modules[g.items.fns[f as usize].module as usize].path
}

pub(crate) fn write(
    g: &mut Gen<'_>,
    fns: &[Callable],
    methods: &[(u32, Vec<Callable>)],
    errors: &[u32],
) {
    let mut s = format!(
        "# Generated by `moddil build --wheel`: the types of the Python module `{}`.\n\nfrom collections.abc import Buffer\nfrom typing import Generic, TypeVar\n\n_T = TypeVar(\"_T\")\n\nclass Error(Exception): ...\nclass Trap(Exception): ...\n\nclass Array(Generic[_T]):\n    def __len__(self) -> int: ...\n    def __getitem__(self, i: int) -> _T: ...\n    def __buffer__(self, flags: int) -> memoryview: ...\n    def tolist(self) -> list[_T]: ...\n\n",
        g.name
    );
    // Each module: the root's items at the top level, a submodule's in a class of its name.
    let mut paths: Vec<Vec<String>> = fns
        .iter()
        .map(|c| fn_module(g, c.f).to_vec())
        .chain(methods.iter().map(|(a, _)| g.module_of(*a).to_vec()))
        .chain(errors.iter().map(|&e| g.module_of(e).to_vec()))
        .collect();
    paths.sort();
    paths.dedup();
    for p in &paths {
        let ind = "    ".repeat(p.len());
        for (k, seg) in p.iter().enumerate() {
            let _ = writeln!(s, "\n{}class {seg}:", "    ".repeat(k));
        }
        for &e in errors.iter().filter(|&&e| g.module_of(e) == p.as_slice()) {
            write_error(g, &mut s, &ind, e);
        }
        for c in fns.iter().filter(|c| fn_module(g, c.f) == p.as_slice()) {
            let name = &g.items.fns[c.f as usize].name;
            let stat = if p.is_empty() {
                String::new()
            } else {
                format!("{ind}@staticmethod\n")
            };
            let _ = writeln!(
                s,
                "\n{stat}{ind}def {name}({}) -> {}: ...",
                sig(g, c, false),
                py(g, &c.ret)
            );
        }
        for (a, ms) in methods
            .iter()
            .filter(|(a, _)| g.module_of(*a) == p.as_slice())
        {
            write_class(g, &mut s, &ind, *a, ms);
        }
        if !p.is_empty() {
            let _ = writeln!(s, "{ind}...");
        }
    }
    g.pyi = s;
}

/// An error's exception class: its fields, or an enum's `variant` and its variants' fields.
fn write_error(g: &Gen<'_>, s: &mut String, ind: &str, e: u32) {
    let mut attrs: Vec<(String, String)> = g
        .fields(e)
        .into_iter()
        .map(|(f, t)| (f, py(g, &t)))
        .collect();
    if g.items.adts[e as usize].is_enum {
        attrs.push(("variant".to_string(), "str".to_string()));
        for k in 0..g.items.adts[e as usize].variants.len() {
            for (f, t) in g.variant_fields(e, k) {
                let f = if f.chars().all(|c| c.is_ascii_digit()) {
                    format!("_{f}")
                } else {
                    f
                };
                if !attrs.iter().any(|(a, _)| *a == f) {
                    attrs.push((f, py(g, &t)));
                }
            }
        }
    }
    if attrs.is_empty() {
        let _ = writeln!(s, "{ind}class {}(Error): ...", g.sname(e));
    } else {
        let _ = writeln!(s, "{ind}class {}(Error):", g.sname(e));
        for (f, t) in attrs {
            let _ = writeln!(s, "{ind}    {f}: {t}");
        }
    }
}

fn write_class(g: &Gen<'_>, s: &mut String, ind: &str, a: u32, ms: &[Callable]) {
    {
        let _ = writeln!(s, "\n{ind}class {}:", g.sname(a));
        for (f, t) in g.fields(a) {
            let _ = writeln!(s, "{ind}    {f}: {}", py(g, &t));
        }
        for m in ms {
            let name = &g.items.fns[m.f as usize].name;
            let own = matches!(m.ret, PyTy::Struct(b, None) if b == a);
            if m.receiver.is_none() && name == "new" && own {
                let ps = sig(g, m, true);
                let _ = writeln!(s, "{ind}    def __init__({ps}) -> None: ...");
            } else if m.receiver.is_some() {
                let _ = writeln!(
                    s,
                    "{ind}    def {name}({}) -> {}: ...",
                    sig(g, m, true),
                    py(g, &m.ret)
                );
            } else {
                let _ = writeln!(
                    s,
                    "{ind}    @staticmethod\n{ind}    def {name}({}) -> {}: ...",
                    sig(g, m, false),
                    py(g, &m.ret)
                );
            }
        }
        let _ = writeln!(s, "{ind}    ...");
    }
}
