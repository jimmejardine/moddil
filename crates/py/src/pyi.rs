//! The `.pyi` stubs: the module's types, for editors and type checkers.

use std::fmt::Write as _;

use crate::{Callable, Gen, PyTy};

fn py(g: &Gen<'_>, t: &PyTy) -> String {
    match t {
        PyTy::Unit => "None".to_string(),
        PyTy::Bool => "bool".to_string(),
        PyTy::Int(..) => "int".to_string(),
        PyTy::Float(..) => "float".to_string(),
        PyTy::Str | PyTy::String => "str".to_string(),
        PyTy::Slice(..) => "Buffer".to_string(),
        PyTy::Vec(e) if e.moddil == "u8" => "bytes".to_string(),
        PyTy::Vec(e) => format!("list[{}]", if e.kind == 'f' { "float" } else { "int" }),
        PyTy::Option(inner) => format!("{} | None", py(g, inner)),
        PyTy::Struct(a, _) => g.sname(*a),
    }
}

fn sig(g: &Gen<'_>, c: &Callable, this: bool) -> String {
    let mut ps: Vec<String> = Vec::new();
    if this {
        ps.push("self".to_string());
    }
    for (n, t) in &c.params {
        ps.push(format!("{n}: {}", py(g, t)));
    }
    ps.join(", ")
}

pub(crate) fn write(g: &mut Gen<'_>, fns: &[Callable], methods: &[(u32, Vec<Callable>)]) {
    let mut s = format!(
        "# Generated by `moddil build --wheel`: the types of the Python module `{}`.\n\nfrom collections.abc import Buffer\n\nclass Error(Exception): ...\nclass Trap(Exception): ...\n",
        g.name
    );
    let mut errors: Vec<&str> = Vec::new();
    for c in fns.iter().chain(methods.iter().flat_map(|(_, m)| m)) {
        if let Some(e) = &c.error
            && !errors.contains(&e.as_str())
        {
            errors.push(e);
            let _ = writeln!(s, "class {e}(Error): ...");
        }
    }
    for c in fns {
        let name = &g.items.fns[c.f as usize].name;
        let _ = writeln!(
            s,
            "\ndef {name}({}) -> {}: ...",
            sig(g, c, false),
            py(g, &c.ret)
        );
    }
    for (a, ms) in methods {
        let _ = writeln!(s, "\nclass {}:", g.sname(*a));
        for (f, t) in g.fields(*a) {
            let _ = writeln!(s, "    {f}: {}", py(g, &t));
        }
        for m in ms {
            let name = &g.items.fns[m.f as usize].name;
            let own = matches!(m.ret, PyTy::Struct(b, None) if b == *a);
            if m.receiver.is_none() && name == "new" && own {
                let ps = sig(g, m, true);
                let _ = writeln!(s, "    def __init__({ps}) -> None: ...");
            } else if m.receiver.is_some() {
                let _ = writeln!(
                    s,
                    "    def {name}({}) -> {}: ...",
                    sig(g, m, true),
                    py(g, &m.ret)
                );
            } else {
                let _ = writeln!(
                    s,
                    "    @staticmethod\n    def {name}({}) -> {}: ...",
                    sig(g, m, false),
                    py(g, &m.ret)
                );
            }
        }
        let _ = writeln!(s, "    ...");
    }
    g.pyi = s;
}
