//! The Lark grammar (Python), for tooling and constrained decoding.
//!
//! Generated from the expanded grammar, so flags are exact; meant for Lark's Earley parser with
//! its dynamic lexer. Python regular expressions make most tokens exact: keywords are excluded
//! from identifiers by lookahead, and raw strings match their closing hashes by back-reference.
//! Two scanner tokens are approximated: block comments and tagged-literal holes nest one level.

use std::collections::HashMap;
use std::fmt::Write as _;

use crate::expand::{Bnf, Sym};
use crate::parse::{Body, Grammar, Quant};
use crate::tokens::{self, Class, Named, Tx};

/// Python regular expressions for the scanner tokens (see the comments in moddil.ebnf).
fn scanner(name: &str) -> &'static str {
    match name {
        "BLOCK_COMMENT" => r"/\*(?:[^*/]|\*(?!/)|/(?!\*)|/\*(?:[^*]|\*(?!/))*\*/)*\*/",
        "RAW_STRING" => r#"b?r(#*)"[\s\S]*?"\1"#,
        "BLOCK_STRING" => r#"r?"""[ \t]*\n(?:[^\n]*\n)*?[ \t]*""""#,
        "TAGGED_STRING" => {
            // The block form first: regex alternation takes the first match, not the longest.
            r#"(?!(?:r|b|br)")[^\W\d]\w*(?:"""[ \t]*\n(?:[^\n]*\n)*?[ \t]*"""|"(?:[^"\\{}]|\\.|\{\{|\}\}|\{(?:[^{}"]|"(?:[^"\\]|\\.)*"|\{[^{}]*\})*\})*"|r(#*)"[\s\S]*?"\1)"#
        }
        _ => panic!("no Lark expression for scanner token `{name}`"),
    }
}

/// Emits the Lark grammar.
pub(crate) fn emit(grammar: &Grammar, bnf: &Bnf) -> String {
    let cleaned = crate::gbnf::cleaned(bnf);
    let names = rule_names(bnf);
    let defs: HashMap<&str, &Body> = grammar
        .rules
        .iter()
        .map(|r| (r.name.as_str(), &r.body))
        .collect();
    let mut out = String::new();
    out.push_str(
        "// Generated by moddil-grammar from reference/grammar/moddil.ebnf: do not edit.\n",
    );
    out.push_str(
        "// Lark, for the Earley parser with the dynamic lexer: Lark(text, parser=\"earley\").\n",
    );
    out.push_str("// Flags are expanded exactly. Block comments and tagged-literal holes nest one level.\n\n");
    let _ = writeln!(out, "start: {}", names[bnf.start as usize]);
    for (n, prods) in cleaned.iter().enumerate() {
        let Some(prods) = prods else { continue };
        let mut alts = Vec::new();
        let mut empty = false;
        for prod in prods {
            if prod.is_empty() {
                empty = true;
                continue;
            }
            let syms: Vec<String> = prod
                .iter()
                .map(|s| match s {
                    Sym::N(m) => names[*m as usize].clone(),
                    Sym::T(t) => terminal(&bnf.terms[*t as usize]),
                })
                .collect();
            alts.push(syms.join(" "));
        }
        let body = match (alts.len(), empty) {
            (0, _) => continue,
            (_, false) => alts.join(" | "),
            (_, true) => format!("({})?", alts.join(" | ")),
        };
        let _ = writeln!(out, "{}: {body}", names[n]);
    }
    out.push_str("\n// Tokens\n");
    for rule in &grammar.rules {
        let Body::Token(def) = &rule.body else {
            continue;
        };
        let regex = match &def.expr {
            Some(expr) => regex(expr, &defs),
            None => scanner(&rule.name).to_string(),
        };
        let _ = writeln!(out, "{}: /{}/", rule.name, regex.replace('/', "\\/"));
    }
    for rule in &grammar.rules {
        if let Body::Token(def) = &rule.body
            && def.skip
        {
            let _ = writeln!(out, "%ignore {}", rule.name);
        }
    }
    out
}

fn rule_names(bnf: &Bnf) -> Vec<String> {
    let mut used: HashMap<String, usize> = HashMap::new();
    bnf.nts
        .iter()
        .map(|nt| {
            let mut s = String::new();
            for c in nt.name.to_ascii_lowercase().chars() {
                match c {
                    'a'..='z' | '0'..='9' => s.push(c),
                    '?' => s.push_str("_opt"),
                    '*' => s.push_str("_rep"),
                    '(' => s.push_str("_grp"),
                    ')' | ']' => {}
                    _ => s.push('_'),
                }
            }
            let mut base = s.trim_matches('_').replace("__", "_");
            if base.starts_with(|c: char| c.is_ascii_digit()) {
                base.insert(0, 'r');
            }
            let n = used.entry(base.clone()).or_insert(0);
            *n += 1;
            if *n == 1 { base } else { format!("{base}_{n}") }
        })
        .collect()
}

fn terminal(term: &str) -> String {
    match term.strip_prefix('\'').and_then(|t| t.strip_suffix('\'')) {
        Some(lit) => format!("\"{}\"", lit.replace('\\', "\\\\").replace('"', "\\\"")),
        None => term.to_string(),
    }
}

fn escape(c: char) -> String {
    match c {
        '\n' => "\\n".to_string(),
        '\t' => "\\t".to_string(),
        '\r' => "\\r".to_string(),
        // `/` is escaped once, for the whole pattern, where it is written out.
        _ if "\\.^$|?*+()[]{}-".contains(c) => format!("\\{c}"),
        _ => c.to_string(),
    }
}

fn class(c: &Class) -> String {
    let mut s = String::from("[");
    if c.negated {
        s.push('^');
    }
    for &(lo, hi) in &c.ranges {
        s.push_str(&escape(lo));
        if hi != lo {
            s.push('-');
            s.push_str(&escape(hi));
        }
    }
    s.push(']');
    s
}

fn regex(t: &Tx, defs: &HashMap<&str, &Body>) -> String {
    match t {
        Tx::Lit(s) => s.chars().map(escape).collect(),
        Tx::Class(c) => class(c),
        Tx::Named(Named::XidStart) => r"[^\W\d]".to_string(),
        Tx::Named(Named::XidContinue) => r"\w".to_string(),
        Tx::Ref(name) => match defs.get(name.as_str()) {
            Some(Body::Token(def)) => match &def.expr {
                Some(e) => format!("(?:{})", regex(e, defs)),
                None => format!("(?:{})", scanner(name)),
            },
            Some(Body::Keywords(words)) => alternation(words),
            _ => panic!("token rule `{name}` is not defined"),
        },
        Tx::Seq(items) => items.iter().map(|i| regex(i, defs)).collect(),
        Tx::Alt(alts) => format!(
            "(?:{})",
            alts.iter()
                .map(|a| regex(a, defs))
                .collect::<Vec<_>>()
                .join("|")
        ),
        Tx::Rep(inner, q) => {
            let op = match q {
                Quant::Opt | Quant::Greedy => "?",
                Quant::Star => "*",
                Quant::Plus => "+",
                Quant::One => "",
            };
            format!("(?:{}){op}", regex(inner, defs))
        }
        Tx::Minus(from, except) => {
            let words = match except.as_ref() {
                Tx::Ref(name) => match defs.get(name.as_str()) {
                    Some(Body::Keywords(words)) => words.clone(),
                    _ => Vec::new(),
                },
                other => tokens::literals(other).unwrap_or_default(),
            };
            format!("(?!{}\\b){}", alternation(&words), regex(from, defs))
        }
    }
}

fn alternation(words: &[String]) -> String {
    let mut sorted: Vec<&String> = words.iter().collect();
    sorted.sort_by_key(|w| std::cmp::Reverse(w.len()));
    format!(
        "(?:{})",
        sorted
            .iter()
            .map(|w| w.chars().map(escape).collect::<String>())
            .collect::<Vec<_>>()
            .join("|")
    )
}
