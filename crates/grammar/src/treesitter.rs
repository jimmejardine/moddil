//! The tree-sitter grammar (`editors/tree-sitter-moddil/grammar.js`).
//!
//! Generated from the rules as written, without expanding flags, so it accepts a little more than
//! Moddil (as an editor wants) and its node names are the grammar's rule names. tree-sitter allows
//! only the start rule to match the empty string: a rule `R ::= X?` (or `X*`) becomes `R ::= X` with
//! every use made optional, and any other rule that can match nothing is inlined where it is used.
//! The four scanner tokens are external, implemented in `src/scanner.c`.

use std::collections::{BTreeSet, HashMap, HashSet};
use std::fmt::Write as _;

use crate::parse::{Alt, Atom, Body, Grammar, Item, Quant, Rule};
use crate::tokens::{Class, Named, Tx};

/// GLR conflicts tree-sitter is told to accept: places where its one token of lookahead is less
/// than the LL(3) grammar needs, or where dropping the flags lets two readings overlap.
/// Found by running `tree-sitter generate` until it stops reporting conflicts; each is a place the
/// LL(3) grammar settles with more lookahead, a greedy optional, or a flag.
const CONFLICTS: &[&[&str]] = &[
    &["use_path"],
    &["literal"],
    &["primary", "block_like"],
    &["vis"],
    &["defer_stmt", "primary"],
    &["jump"],
    &["range"],
    &["primary"],
    &["impl_item", "primary"],
    &["in_operand"],
    &["postfix_op"],
    &["pattern_no_alt", "pattern_path"],
    &["and_operand"],
    &["if_expr"],
];

/// How a nullable rule is emitted.
enum Nullable {
    /// `R ::= X?` or `X*`: defined as `X` (or `repeat1`), and every use is optional.
    Unwrapped,
    /// Inlined at every use.
    Inlined,
}

struct Gen<'g> {
    rules: HashMap<&'g str, &'g Rule>,
    nullable: HashMap<&'g str, Nullable>,
}

/// Emits `grammar.js`.
pub(crate) fn emit(grammar: &Grammar) -> String {
    let rules: HashMap<&str, &Rule> = grammar.rules.iter().map(|r| (r.name.as_str(), r)).collect();
    let nullable = nullable_rules(grammar);
    let g = Gen { rules, nullable };
    let token_names = used_tokens(grammar);
    let mut out = String::new();
    out.push_str(
        "// Generated by moddil-grammar from reference/grammar/moddil.ebnf: do not edit.\n",
    );
    out.push_str(
        "// The rules as written, without flags: it accepts a little more than Moddil.\n\n",
    );
    out.push_str("module.exports = grammar({\n  name: 'moddil',\n  word: $ => $.ident,\n");
    out.push_str("  extras: $ => [/[ \\t\\r\\n]+/, $.line_comment, $.block_comment],\n");
    let externals: Vec<String> = grammar
        .rules
        .iter()
        .filter(|r| matches!(&r.body, Body::Token(d) if d.scanner))
        .map(|r| format!("$.{}", r.name.to_ascii_lowercase()))
        .collect();
    let _ = writeln!(out, "  externals: $ => [{}],", externals.join(", "));
    let conflicts: Vec<String> = CONFLICTS
        .iter()
        .map(|set| {
            format!(
                "[{}]",
                set.iter()
                    .map(|n| format!("$.{n}"))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        })
        .collect();
    let _ = writeln!(out, "  conflicts: $ => [{}],", conflicts.join(", "));
    out.push_str("  rules: {\n");
    // tree-sitter starts from the first rule: `file`.
    let mut ordered: Vec<&Rule> = grammar.rules.iter().collect();
    ordered.sort_by_key(|r| r.name != "file");
    for rule in ordered {
        let body = match &rule.body {
            Body::Syntax(alt) => {
                if matches!(g.nullable.get(rule.name.as_str()), Some(Nullable::Inlined))
                    && rule.name != "file"
                {
                    continue;
                }
                g.rule_body(rule, alt)
            }
            Body::Keywords(words) if token_names.contains(rule.name.as_str()) => {
                format!(
                    "choice({})",
                    words
                        .iter()
                        .map(|w| js_string(w))
                        .collect::<Vec<_>>()
                        .join(", ")
                )
            }
            Body::Token(def) if !def.scanner && token_names.contains(rule.name.as_str()) => {
                let expr = def.expr.as_ref().expect("a regular token");
                format!("token({})", regex(expr, &g.rules))
            }
            _ => continue,
        };
        let _ = writeln!(out, "    {}: $ => {body},", js_name(&rule.name));
    }
    out.push_str("  },\n});\n");
    out
}

/// Token rules named by syntax rules (fragments are inlined into the tokens that use them), plus
/// the skipped line comment.
fn used_tokens(grammar: &Grammar) -> HashSet<&str> {
    let mut used = BTreeSet::new();
    for rule in &grammar.rules {
        if let Body::Syntax(alt) = &rule.body {
            refs(alt, &mut used);
        }
    }
    used.insert("LINE_COMMENT");
    used.into_iter().collect()
}

/// Every rule an alternative refers to.
pub(crate) fn refs<'a>(alt: &'a Alt, used: &mut BTreeSet<&'a str>) {
    for seq in &alt.0 {
        for item in &seq.items {
            match &item.atom {
                Atom::Ref { name, .. } => {
                    used.insert(name.as_str());
                }
                Atom::Group(inner) => refs(inner, used),
                Atom::Term(_) => {}
            }
        }
    }
}

fn js_name(name: &str) -> String {
    if crate::parse::is_token_name(name) {
        name.to_ascii_lowercase()
    } else {
        name.to_string()
    }
}

fn js_string(s: &str) -> String {
    format!("'{}'", s.replace('\\', "\\\\").replace('\'', "\\'"))
}

/// Which syntax rules can match the empty string (guards ignored), and how each is emitted.
fn nullable_rules(grammar: &Grammar) -> HashMap<&str, Nullable> {
    let syntax: Vec<(&str, &Alt)> = grammar
        .rules
        .iter()
        .filter_map(|r| match &r.body {
            Body::Syntax(alt) => Some((r.name.as_str(), alt)),
            _ => None,
        })
        .collect();
    let mut null: HashSet<&str> = HashSet::new();
    let mut changed = true;
    while changed {
        changed = false;
        for (name, alt) in &syntax {
            if !null.contains(name) && alt_nullable(alt, &null) {
                null.insert(name);
                changed = true;
            }
        }
    }
    syntax
        .iter()
        .filter(|(name, _)| null.contains(name))
        .map(|(name, alt)| {
            let unwrapped = matches!(alt.0.as_slice(), [seq] if seq.items.len() == 1
                && matches!(seq.items[0].quant, Quant::Opt | Quant::Greedy | Quant::Star));
            (
                *name,
                if unwrapped {
                    Nullable::Unwrapped
                } else {
                    Nullable::Inlined
                },
            )
        })
        .collect()
}

fn alt_nullable(alt: &Alt, null: &HashSet<&str>) -> bool {
    alt.0.iter().any(|seq| {
        seq.items.iter().all(|item| {
            matches!(item.quant, Quant::Opt | Quant::Greedy | Quant::Star)
                || match &item.atom {
                    Atom::Term(_) => false,
                    Atom::Ref { name, .. } => null.contains(name.as_str()),
                    Atom::Group(inner) => alt_nullable(inner, null),
                }
        })
    })
}

impl Gen<'_> {
    fn rule_body(&self, rule: &Rule, alt: &Alt) -> String {
        if let Some(Nullable::Unwrapped) = self.nullable.get(rule.name.as_str())
            && let [seq] = alt.0.as_slice()
        {
            let item = &seq.items[0];
            let inner = self.atom(&item.atom);
            return if item.quant == Quant::Star {
                format!("repeat1({inner})")
            } else {
                inner
            };
        }
        self.alt(alt)
    }

    fn alt(&self, alt: &Alt) -> String {
        let seqs: Vec<String> = alt.0.iter().map(|seq| self.seq(&seq.items)).collect();
        if seqs.len() == 1 {
            seqs.into_iter().next().expect("one")
        } else {
            format!("choice({})", seqs.join(", "))
        }
    }

    fn seq(&self, items: &[Item]) -> String {
        let parts: Vec<String> = items.iter().map(|i| self.item(i)).collect();
        match parts.len() {
            0 => "blank()".to_string(),
            1 => parts.into_iter().next().expect("one"),
            _ => format!("seq({})", parts.join(", ")),
        }
    }

    fn item(&self, item: &Item) -> String {
        let base = self.atom(&item.atom);
        // A use of an unwrapped nullable rule is itself optional.
        let unwrapped = matches!(&item.atom, Atom::Ref { name, .. }
            if matches!(self.nullable.get(name.as_str()), Some(Nullable::Unwrapped)));
        match item.quant {
            Quant::One if unwrapped => format!("optional({base})"),
            Quant::One => base,
            Quant::Opt | Quant::Greedy => format!("optional({base})"),
            Quant::Star => format!("repeat({base})"),
            Quant::Plus if unwrapped => format!("repeat({base})"),
            Quant::Plus => format!("repeat1({base})"),
        }
    }

    fn atom(&self, atom: &Atom) -> String {
        match atom {
            Atom::Term(t) => js_string(t),
            Atom::Group(inner) => self.alt(inner),
            Atom::Ref { name, .. } => match self.nullable.get(name.as_str()) {
                Some(Nullable::Inlined) => match &self.rules[name.as_str()].body {
                    Body::Syntax(alt) => self.alt(alt),
                    _ => unreachable!("only syntax rules are inlined"),
                },
                _ => format!("$.{}", js_name(name)),
            },
        }
    }
}

fn escape(c: char) -> String {
    match c {
        '\n' => "\\n".to_string(),
        '\t' => "\\t".to_string(),
        '\r' => "\\r".to_string(),
        _ if "\\/.^$|?*+()[]{}-".contains(c) => format!("\\{c}"),
        _ => c.to_string(),
    }
}

fn class(c: &Class) -> String {
    let mut s = String::from("[");
    if c.negated {
        s.push('^');
    }
    for &(lo, hi) in &c.ranges {
        s.push_str(&escape(lo));
        if hi != lo {
            s.push('-');
            s.push_str(&escape(hi));
        }
    }
    s.push(']');
    s
}

/// A tree-sitter regular expression (a JavaScript regex literal).
fn regex(t: &Tx, rules: &HashMap<&str, &Rule>) -> String {
    format!("/{}/", pattern(t, rules))
}

fn pattern(t: &Tx, rules: &HashMap<&str, &Rule>) -> String {
    match t {
        Tx::Lit(s) => s.chars().map(escape).collect(),
        Tx::Class(c) => class(c),
        Tx::Named(Named::XidStart) => r"\p{XID_Start}".to_string(),
        Tx::Named(Named::XidContinue) => r"\p{XID_Continue}".to_string(),
        Tx::Ref(name) => match &rules[name.as_str()].body {
            Body::Token(def) => format!(
                "({})",
                pattern(def.expr.as_ref().expect("a regular fragment"), rules)
            ),
            _ => panic!("token `{name}` refers to a non-token rule"),
        },
        Tx::Seq(items) => items.iter().map(|i| pattern(i, rules)).collect(),
        Tx::Alt(alts) => format!(
            "({})",
            alts.iter()
                .map(|a| pattern(a, rules))
                .collect::<Vec<_>>()
                .join("|")
        ),
        Tx::Rep(inner, q) => {
            let op = match q {
                Quant::Opt | Quant::Greedy => "?",
                Quant::Star => "*",
                Quant::Plus => "+",
                Quant::One => "",
            };
            format!("({}){op}", pattern(inner, rules))
        }
        // Keywords are kept out of identifiers by `word`, so the exclusion is not written.
        Tx::Minus(from, _) => pattern(from, rules),
    }
}
