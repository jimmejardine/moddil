//! The GBNF grammar (llama.cpp's format) for constrained decoding by models.
//!
//! Generated from the expanded grammar, so flags are exact; terminals are followed by optional
//! whitespace and comments. Character-level GBNF has no lexer, so it accepts a little more than
//! Moddil: keywords are not excluded from identifiers, identifier characters are approximated, and
//! raw-string contents are not checked for their closing hashes.

use std::collections::HashMap;
use std::fmt::Write as _;

use crate::expand::{Bnf, Sym};
use crate::parse::{Body, Grammar, Quant};
use crate::tokens::{Class, Named, Tx};

/// Rules every scanner token and built-in class is written as, by hand.
const NATIVE: &str = r####"# Built-in classes (approximated: any non-ASCII character in the BMP counts as a letter).
xid-start ::= [a-zA-Z\u0080-￿]
xid-continue ::= [a-zA-Z0-9_\u0080-￿]
# Scanner tokens (see the comments in moddil.ebnf).
tok-block-comment ::= "/*" block-comment-item* "*"+ "/"
block-comment-item ::= tok-block-comment | [^*/] | "/" [^*/] | "*"+ [^*/]
tok-raw-string ::= "b"? "r" ( "\"" [^"]* "\"" | "#\"" raw-char* "\"#" | "##\"" raw-char* "\"##" | "###\"" raw-char* "\"###" )
raw-char ::= [^"] | "\""
tok-block-string ::= "r"? "\"\"\"" [ \t]* "\n" ( [^\n]* "\n" )* [ \t]* "\"\"\""
tok-tagged-string ::= tok-tag ( tagged-body | tok-raw-string | tok-block-string )
tagged-body ::= "\"" ( [^"\\{}] | tok-escape | "{{" | "}}" | "{" hole* "}" )* "\""
hole ::= [^{}"] | tok-string | "{" hole* "}"
"####;

/// Emits the GBNF grammar.
pub(crate) fn emit(grammar: &Grammar, bnf: &Bnf) -> String {
    let cleaned = cleaned(bnf);
    let names = rule_names(bnf);
    let mut out = String::new();
    out.push_str(
        "# Generated by moddil-grammar from reference/grammar/moddil.ebnf: do not edit.\n",
    );
    out.push_str(
        "# GBNF (llama.cpp) for constrained decoding. Flags are expanded exactly; it accepts a\n",
    );
    out.push_str(
        "# little more than Moddil: keywords are not excluded from identifiers, identifier\n",
    );
    out.push_str("# characters are approximated, and raw-string contents are not checked.\n\n");
    let _ = writeln!(out, "root ::= ws {}", names[bnf.start as usize]);
    out.push_str("ws ::= ( tok-whitespace | tok-line-comment | tok-block-comment )*\n\n");
    for (n, prods) in cleaned.iter().enumerate() {
        let Some(prods) = prods else { continue };
        let (mut alts, empty) = alternatives(prods, bnf, &names, terminal);
        let body = match (alts.len(), empty) {
            (0, _) => "\"\"".to_string(),
            (1, false) => alts.remove(0),
            (_, false) => alts.join(" | "),
            (_, true) => format!("( {} )?", alts.join(" | ")),
        };
        let _ = writeln!(out, "{} ::= {body}", names[n]);
    }
    out.push_str("\n# Tokens\n");
    for rule in &grammar.rules {
        if let Body::Token(def) = &rule.body
            && let Some(expr) = &def.expr
        {
            let _ = writeln!(out, "{} ::= {}", token_name(&rule.name), tx(expr));
        }
    }
    out.push_str(NATIVE);
    out
}

/// GBNF rule names allow only letters, digits and `-`.
fn sanitise(name: &str) -> String {
    let mut s = String::new();
    for c in name.chars() {
        match c {
            'a'..='z' | 'A'..='Z' | '0'..='9' => s.push(c),
            '?' => s.push_str("-opt"),
            '*' => s.push_str("-rep"),
            '(' => s.push_str("-grp"),
            ')' | ']' => {}
            _ => s.push('-'),
        }
    }
    s.trim_matches('-').replace("--", "-")
}

fn rule_names(bnf: &Bnf) -> Vec<String> {
    let mut used: HashMap<String, usize> = HashMap::new();
    bnf.nts
        .iter()
        .map(|nt| {
            let base = sanitise(&nt.name);
            let n = used.entry(base.clone()).or_insert(0);
            *n += 1;
            if *n == 1 { base } else { format!("{base}-{n}") }
        })
        .collect()
}

fn token_name(name: &str) -> String {
    format!("tok-{}", sanitise(&name.to_ascii_lowercase()))
}

/// A terminal of the expanded grammar, followed by whitespace.
fn terminal(term: &str) -> String {
    match term.strip_prefix('\'').and_then(|t| t.strip_suffix('\'')) {
        Some(lit) => format!("{} ws", literal(lit)),
        None => format!("{} ws", token_name(term)),
    }
}

fn literal(text: &str) -> String {
    let mut s = String::from("\"");
    for c in text.chars() {
        match c {
            '"' => s.push_str("\\\""),
            '\\' => s.push_str("\\\\"),
            '\n' => s.push_str("\\n"),
            '\t' => s.push_str("\\t"),
            '\r' => s.push_str("\\r"),
            _ => s.push(c),
        }
    }
    s.push('"');
    s
}

fn class(c: &Class) -> String {
    let esc = |ch: char| match ch {
        '\n' => "\\n".to_string(),
        '\t' => "\\t".to_string(),
        '\r' => "\\r".to_string(),
        '\\' | ']' | '[' | '^' | '-' => format!("\\{ch}"),
        _ => ch.to_string(),
    };
    let mut s = String::from("[");
    if c.negated {
        s.push('^');
    }
    for &(lo, hi) in &c.ranges {
        s.push_str(&esc(lo));
        if hi != lo {
            s.push('-');
            s.push_str(&esc(hi));
        }
    }
    s.push(']');
    s
}

fn tx(t: &Tx) -> String {
    match t {
        Tx::Lit(s) => literal(s),
        Tx::Class(c) => class(c),
        Tx::Named(Named::XidStart) => "xid-start".to_string(),
        Tx::Named(Named::XidContinue) => "xid-continue".to_string(),
        Tx::Ref(name) => token_name(name),
        Tx::Seq(items) => items.iter().map(tx).collect::<Vec<_>>().join(" "),
        Tx::Alt(alts) => format!(
            "( {} )",
            alts.iter().map(tx).collect::<Vec<_>>().join(" | ")
        ),
        Tx::Rep(inner, q) => {
            let s = match inner.as_ref() {
                Tx::Seq(_) | Tx::Minus(..) => format!("( {} )", tx(inner)),
                _ => tx(inner),
            };
            let op = match q {
                Quant::Opt | Quant::Greedy => "?",
                Quant::Star => "*",
                Quant::Plus => "+",
                Quant::One => "",
            };
            format!("{s}{op}")
        }
        // Character-level GBNF cannot subtract: accept what `A` matches.
        Tx::Minus(from, _) => tx(from),
    }
}

/// A rule's productions as alternatives, each its symbols joined by spaces (a rule by its name
/// in `names`, a terminal as `terminal` writes it), and whether one of them is empty, which is
/// left out.
pub(crate) fn alternatives(
    prods: &[Vec<Sym>],
    bnf: &Bnf,
    names: &[String],
    terminal: impl Fn(&str) -> String,
) -> (Vec<String>, bool) {
    let mut alts = Vec::new();
    let mut empty = false;
    for prod in prods {
        if prod.is_empty() {
            empty = true;
            continue;
        }
        let syms: Vec<String> = prod
            .iter()
            .map(|s| match s {
                Sym::N(m) => names[*m as usize].clone(),
                Sym::T(t) => terminal(&bnf.terms[*t as usize]),
            })
            .collect();
        alts.push(syms.join(" "));
    }
    (alts, empty)
}

/// The productions to emit: unproductive ones dropped, and references to nonterminals that only
/// derive the empty string left out. `None` for a nonterminal that is not emitted.
pub(crate) fn cleaned(bnf: &Bnf) -> Vec<Option<Vec<Vec<Sym>>>> {
    let ok = productive(bnf);
    let mut prods: Vec<Option<Vec<Vec<Sym>>>> = bnf
        .nts
        .iter()
        .enumerate()
        .map(|(n, def)| {
            ok[n].then(|| {
                def.prods
                    .iter()
                    .filter(|p| {
                        p.iter()
                            .all(|s| !matches!(s, Sym::N(m) if !ok[*m as usize]))
                    })
                    .cloned()
                    .collect()
            })
        })
        .collect();
    loop {
        let empty_only: Vec<bool> = prods
            .iter()
            .map(|p| p.as_ref().is_some_and(|ps| ps.iter().all(Vec::is_empty)))
            .collect();
        if !empty_only.iter().any(|&e| e) {
            return prods;
        }
        for ps in prods.iter_mut().flatten() {
            for prod in ps.iter_mut() {
                prod.retain(|s| !matches!(s, Sym::N(m) if empty_only[*m as usize]));
            }
            ps.dedup();
        }
        for (n, e) in empty_only.iter().enumerate() {
            if *e {
                prods[n] = None;
            }
        }
    }
}

/// Nonterminals that derive at least one terminal string.
fn productive(bnf: &Bnf) -> Vec<bool> {
    let mut ok = vec![false; bnf.nts.len()];
    let mut changed = true;
    while changed {
        changed = false;
        for (n, def) in bnf.nts.iter().enumerate() {
            if !ok[n]
                && def.prods.iter().any(|p| {
                    p.iter().all(|s| {
                        matches!(s, Sym::T(_)) || matches!(s, Sym::N(m) if ok[*m as usize])
                    })
                })
            {
                ok[n] = true;
                changed = true;
            }
        }
    }
    ok
}
