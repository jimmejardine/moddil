//! `moddil build --wasm`: a program's `main` as files to run in a browser or in Node
//! (`compiler.md`: core modules plus generated JS glue):
//! - `name.mjs`, the glue: the shared core ([`core.mjs`](core.mjs)), the program's layout, the
//!   shim, and `run()`, which loads the two modules beside it and runs `main`;
//! - `name.wasm`, the program's module, and `moddil-rt.wasm`, the runtime's;
//! - `name.html`, a page that runs it and shows what it writes and its exit code.

use moddil_sema::{Db, Program};

use crate::compile::compile_main;
use crate::module::{RECORD_WORDS, shim};

/// The runtime module's file name, beside the glue.
pub const RUNTIME_FILE: &str = "moddil-rt.wasm";

/// A program built for the web: each file's name and contents.
pub struct Package {
    /// The glue's file name (`name.mjs`) and its text.
    pub glue: (String, String),
    /// The program's module (`name.wasm`).
    pub program: (String, Vec<u8>),
    /// The runtime's module ([`RUNTIME_FILE`]).
    pub runtime: (String, &'static [u8]),
    /// The page (`name.html`).
    pub html: (String, String),
}

fn base64(bytes: &[u8]) -> String {
    const A: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::new();
    for c in bytes.chunks(3) {
        let n = (u32::from(c[0]) << 16)
            | (u32::from(*c.get(1).unwrap_or(&0)) << 8)
            | u32::from(*c.get(2).unwrap_or(&0));
        for k in 0..4 {
            if k <= c.len() {
                out.push(A[((n >> (18 - 6 * k)) & 63) as usize] as char);
            } else {
                out.push('=');
            }
        }
    }
    out
}

/// Builds `main` (function `main` of `program`) as the files named after `name`.
///
/// # Errors
///
/// What the program reaches that is not compiled to WASM yet, and a `main` that gives other
/// than `()` or `ExitCode`.
pub fn package(db: &dyn Db, program: Program, main: u32, name: &str) -> Result<Package, String> {
    let c = compile_main(db, program, main)?;
    let l = c.layout;
    let wasm = format!("{name}.wasm");
    let layout = format!(
        "{{ pages: {}, table: {}, out: {}, err: {}, record: {}, words: {RECORD_WORDS}, \
         dataFrom: {}, dataTo: {}, siteCount: {}, sites: {}, strings: {}, tasks: {} }}",
        l.pages,
        l.table,
        l.out,
        l.err,
        l.record,
        l.data.0,
        l.data.1,
        l.sites.0,
        l.sites.1,
        l.sites.2,
        l.tasks
    );
    let glue = format!(
        "{core}
// ---- {name}: generated by `moddil build --wasm` --------------------------------------------

const LAYOUT = {layout};
const SHIM = '{shim}';
const PROGRAM = '{wasm}';
const RUNTIME = '{RUNTIME_FILE}';
/** The exit code of a run that trapped (`EX_SOFTWARE`, as a native build's). */
const TRAPPED = 70;

const inNode = typeof process === 'object' && !!process.versions?.node;

/** The bytes of `file`, beside this module: read from disk in Node, fetched in a browser. */
async function load(file) {{
  const url = new URL(file, import.meta.url);
  if (inNode) {{
    const fs = await import('node:fs/promises');
    return fs.readFile(url);
  }}
  const r = await fetch(url);
  if (!r.ok) throw new Error(`fetching ${{url}}: ${{r.status}}`);
  return new Uint8Array(await r.arrayBuffer());
}}

/**
 * Runs the program's `main`: the log, and a trap, go to `error` (by default the console's);
 * its exit code (`main.exit.1`; 70 after a trap).
 */
export async function run({{ error = (s) => console.error(s) }} = {{}}) {{
  if (inNode) {{
    // JSPI's stacks grow, so recursion reaches the interpreters' limit (as the test host).
    const v8 = await import('node:v8');
    v8.setFlagsFromString('--experimental-wasm-growable-stacks');
    v8.setFlagsFromString('--stack-size=200000');
  }}
  const shim = Uint8Array.from(atob(SHIM), (c) => c.charCodeAt(0));
  const [runtime, program] = await Promise.all([load(RUNTIME), load(PROGRAM)]);
  const p = await instantiate({{
    runtime,
    shim,
    program,
    layout: LAYOUT,
    observe: () => {{}},
    log: (level, text) => error(`[${{level}}] ${{text}}`),
    promisingAlways: true,
  }});
  let status;
  try {{
    status = await p.run(0);
  }} catch (e) {{
    error(`the run stopped: ${{e}}`);
    return TRAPPED;
  }}
  if (status === 0) {{
    const code = p.exitCode();
    if ((await p.drop(0)) === 0) return code;
  }}
  const t = p.trapText();
  error(`trap: ${{t.class || 'trap'}}`);
  if (t.at) error(`  at ${{t.at}}`);
  return TRAPPED;
}}

// Run directly by Node (`node {name}.mjs`): it exits with the program's exit code.
if (inNode && import.meta.main) {{
  run().then((code) => {{
    process.exitCode = code;
  }});
}}
",
        core = include_str!("core.mjs"),
        shim = base64(&shim()),
    );
    let html = format!(
        r#"<!doctype html>
<html lang="en">
<meta charset="utf-8">
<title>{name}</title>
<pre id="out"></pre>
<script type="module">
  import {{ run }} from './{name}.mjs';
  const out = document.getElementById('out');
  const write = (s) => {{ out.textContent += s + '\n'; }};
  const code = await run({{ error: write }});
  document.body.dataset.exit = String(code);
  write(`exit ${{code}}`);
</script>
</html>
"#
    );
    Ok(Package {
        glue: (format!("{name}.mjs"), glue),
        program: (wasm, c.bytes),
        runtime: (RUNTIME_FILE.to_string(), crate::runtime::BYTES),
        html: (format!("{name}.html"), html),
    })
}

#[cfg(test)]
mod tests {
    #[test]
    fn base64_pads_as_the_standard_says() {
        assert_eq!(super::base64(b"Man"), "TWFu");
        assert_eq!(super::base64(b"Ma"), "TWE=");
        assert_eq!(super::base64(b"M"), "TQ==");
    }
}
